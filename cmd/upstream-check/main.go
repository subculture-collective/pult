// Command upstream-check reports what moved upstream since Theme Tender
// last looked: catalog sources whose default branch is past the pinned
// revision in catalog/sources.json, and apps whose newest release tag is
// newer than the version their registry entry was checked against. CI runs
// it weekly and keeps one tracking issue up to date; see
// .gitea/workflows/upstream-watch.yml.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"
)

// IssueTitle is the title of the tracking issue the report is kept in.
const IssueTitle = "Upstream watcher report"

// appRepos maps registry ids to the repository whose tags are the app's
// releases, for apps whose homepage is not that repository.
var appRepos = map[string]string{
	"alacritty": "https://github.com/alacritty/alacritty",
	"btop":      "https://github.com/aristocratos/btop",
	"ghostty":   "https://github.com/ghostty-org/ghostty",
	"kitty":     "https://github.com/kovidgoyal/kitty",
	"starship":  "https://github.com/starship/starship",
	"tmux":      "https://github.com/tmux/tmux",
	"yazi":      "https://github.com/sxyazi/yazi",
}

// Remote runs `git ls-remote` with args and returns what it prints.
type Remote func(args ...string) (string, error)

func gitLsRemote(args ...string) (string, error) {
	cmd := exec.Command("git", append([]string{"ls-remote"}, args...)...)
	cmd.Env = append(os.Environ(), "GIT_TERMINAL_PROMPT=0")
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("git ls-remote %s: %w", strings.Join(args, " "), err)
	}
	return string(out), nil
}

func main() {
	root := flag.String("root", ".", "repository root")
	issue := flag.Bool("issue", false, "create or update the tracking issue (needs GITEA_TOKEN, GITHUB_SERVER_URL and GITHUB_REPOSITORY)")
	flag.Parse()
	report, err := Check(*root, gitLsRemote)
	if err != nil {
		fmt.Fprintln(os.Stderr, "upstream-check:", err)
		os.Exit(1)
	}
	fmt.Print(report)
	if *issue {
		api := strings.TrimRight(os.Getenv("GITHUB_SERVER_URL"), "/") + "/api/v1/repos/" + os.Getenv("GITHUB_REPOSITORY")
		n, err := updateIssue(&http.Client{Timeout: time.Minute}, api, os.Getenv("GITEA_TOKEN"), report)
		if err != nil {
			fmt.Fprintln(os.Stderr, "upstream-check:", err)
			os.Exit(1)
		}
		fmt.Fprintf(os.Stderr, "updated issue #%d\n", n)
	}
}

type source struct {
	ID       string `json:"id"`
	URL      string `json:"url"`
	Revision string `json:"revision"`
}

// checkedRE matches the first line of a registry entry's header comment,
// "# Checked on Arch, lazygit 0.66.2, 2026-11-06: ...".
var checkedRE = regexp.MustCompile(`^# Checked on [^,]+, \S+ ([0-9][0-9A-Za-z.]*), `)

var (
	idRE       = regexp.MustCompile(`(?m)^id: (\S+)`)
	homepageRE = regexp.MustCompile(`(?m)^homepage: (https://github\.com/[^/\s]+/[^/\s]+)`)
	tagRE      = regexp.MustCompile(`^v?([0-9]+(?:\.[0-9]+)+[a-z]?)$`)
)

// Check builds the report as Markdown.
func Check(root string, remote Remote) (string, error) {
	var b strings.Builder
	b.WriteString("Generated by `cmd/upstream-check`. Each run replaces this text.\n\n")

	raw, err := os.ReadFile(filepath.Join(root, "catalog", "sources.json"))
	if err != nil {
		return "", err
	}
	var src struct{ Sources []source }
	if err := json.Unmarshal(raw, &src); err != nil {
		return "", fmt.Errorf("catalog/sources.json: %w", err)
	}
	b.WriteString("## Catalog sources\n\n| Source | Pinned | Upstream HEAD | |\n|---|---|---|---|\n")
	for _, s := range src.Sources {
		out, err := remote(s.URL, "HEAD")
		head, state := "", ""
		switch {
		case err != nil:
			head, state = "?", "lookup failed: "+err.Error()
		default:
			head = strings.Fields(out + " ")[0]
			if head == s.Revision {
				state = "current"
			} else {
				state = "**moved**: re-pin and rebuild the catalog"
			}
		}
		fmt.Fprintf(&b, "| [%s](%s) | `%s` | `%s` | %s |\n", s.ID, s.URL, short(s.Revision), short(head), state)
	}

	entries, err := filepath.Glob(filepath.Join(root, "registry", "apps", "*.yaml"))
	if err != nil {
		return "", err
	}
	slices.Sort(entries)
	b.WriteString("\n## Apps\n\n| App | Checked against | Newest tag | |\n|---|---|---|---|\n")
	for _, e := range entries {
		raw, err := os.ReadFile(e)
		if err != nil {
			return "", err
		}
		m := idRE.FindSubmatch(raw)
		if m == nil {
			return "", fmt.Errorf("%s: no id", e)
		}
		id := string(m[1])
		checked := ""
		if m := checkedRE.FindSubmatch(raw); m != nil {
			checked = string(m[1])
		}
		repo := appRepos[id]
		if m := homepageRE.FindSubmatch(raw); repo == "" && m != nil {
			repo = string(m[1])
		}
		newest, state := "?", ""
		if repo == "" {
			state = "no release repository known; add one to appRepos in cmd/upstream-check"
		} else if out, err := remote("--tags", "--refs", repo); err != nil {
			state = "lookup failed: " + err.Error()
		} else if newest = newestTag(out); newest == "" {
			newest, state = "?", "no release tags"
		}
		switch {
		case state != "":
		case checked == "":
			state = "never checked against an installed copy"
		case newer(newest, checked):
			state = "**newer release**: check the entry against it"
		default:
			state = "current"
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", id, orDash(checked), newest, state)
	}
	return b.String(), nil
}

// newestTag picks the highest release version among ls-remote tag lines,
// ignoring prereleases and tags that are not versions.
func newestTag(lsRemote string) string {
	best := ""
	for _, l := range strings.Split(lsRemote, "\n") {
		f := strings.Fields(l)
		if len(f) != 2 {
			continue
		}
		m := tagRE.FindStringSubmatch(strings.TrimPrefix(f[1], "refs/tags/"))
		if m != nil && (best == "" || newer(m[1], best)) {
			best = m[1]
		}
	}
	return best
}

// newer compares dotted versions with an optional letter suffix (tmux's
// 3.5a): numbers first, then the suffix.
func newer(a, b string) bool {
	na, sa := splitVersion(a)
	nb, sb := splitVersion(b)
	for i := range max(len(na), len(nb)) {
		var x, y int
		if i < len(na) {
			x = na[i]
		}
		if i < len(nb) {
			y = nb[i]
		}
		if x != y {
			return x > y
		}
	}
	return sa > sb
}

func splitVersion(v string) ([]int, string) {
	suffix := strings.TrimLeft(v, "0123456789.")
	var out []int
	for _, p := range strings.Split(strings.TrimSuffix(v, suffix), ".") {
		n, _ := strconv.Atoi(p)
		out = append(out, n)
	}
	return out, suffix
}

func short(rev string) string {
	if len(rev) > 12 {
		return rev[:12]
	}
	return rev
}

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

// updateIssue replaces the body of the open tracking issue, or opens it.
func updateIssue(c *http.Client, api, token, body string) (int, error) {
	if token == "" {
		return 0, errors.New("GITEA_TOKEN is not set")
	}
	call := func(method, path string, in any, out any) error {
		var rd io.Reader
		if in != nil {
			b, err := json.Marshal(in)
			if err != nil {
				return err
			}
			rd = bytes.NewReader(b)
		}
		req, err := http.NewRequest(method, api+path, rd)
		if err != nil {
			return err
		}
		req.Header.Set("Authorization", "token "+token)
		req.Header.Set("Content-Type", "application/json")
		resp, err := c.Do(req)
		if err != nil {
			return err
		}
		defer resp.Body.Close()
		if resp.StatusCode >= 300 {
			msg, _ := io.ReadAll(io.LimitReader(resp.Body, 512))
			return fmt.Errorf("%s %s: %s: %s", method, path, resp.Status, bytes.TrimSpace(msg))
		}
		if out != nil {
			return json.NewDecoder(resp.Body).Decode(out)
		}
		return nil
	}
	var open []struct {
		Number int    `json:"number"`
		Title  string `json:"title"`
	}
	if err := call("GET", "/issues?state=open&type=issues&limit=50&q="+strings.ReplaceAll(IssueTitle, " ", "+"), nil, &open); err != nil {
		return 0, err
	}
	for _, i := range open {
		if i.Title == IssueTitle {
			return i.Number, call("PATCH", fmt.Sprintf("/issues/%d", i.Number), map[string]string{"body": body}, nil)
		}
	}
	var created struct {
		Number int `json:"number"`
	}
	err := call("POST", "/issues", map[string]string{"title": IssueTitle, "body": body}, &created)
	return created.Number, err
}
