// Package omarchy is Pult's Omarchy backend. It writes a theme
// directory under ~/.config/omarchy/themes and switches to it with
// omarchy-theme-set, so Omarchy renders every app it themes from its own
// templates. It never edits files Omarchy owns.
package omarchy

import (
	"fmt"
	"path/filepath"
	"regexp"
	"strings"

	"git.subcult.tv/subculture-collective/pult/internal/changes"
	"git.subcult.tv/subculture-collective/pult/internal/color"
	"git.subcult.tv/subculture-collective/pult/internal/render"
)

// Prefix keeps Pult's themes apart from Omarchy's own. A user
// theme with the same name as a built-in one is overlaid on it, which
// would mix in the built-in theme's backgrounds and editor themes.
const Prefix = "pult-"

var nonName = regexp.MustCompile(`[^a-z0-9-]+`)

// Name is the Omarchy theme name for a Pult theme slug, already in
// the form omarchy-theme-set normalises names to.
func Name(slug string) string {
	return Prefix + strings.Trim(nonName.ReplaceAllString(strings.ToLower(slug), "-"), "-")
}

// ThemeDir is where omarchy-theme-set looks for user themes. Omarchy
// hard-codes $HOME/.config/omarchy/themes, so XDG_CONFIG_HOME is not used.
func ThemeDir(home, slug string) string {
	return filepath.Join(home, ".config", "omarchy", "themes", Name(slug))
}

// SwitchCommand switches Omarchy to a theme. Running it is the caller's
// job, after the theme directory is written through the change record.
func SwitchCommand(name string) []string { return []string{"omarchy-theme-set", name} }

// keys maps Omarchy's colors.toml keys to roles. Omarchy uses background,
// foreground, muted and bright_foreground as ANSI 0, 7, 8 and 15, and
// derives brown and any key left out.
var keys = []struct {
	key  string
	role color.Role
}{
	{"accent", color.Blue},
	{"selection", color.SelectionBG},
	{"selection_background", color.SelectionBG},
	{"selection_foreground", color.SelectionFG},
	{"muted", color.ANSI8},
	{"", ""},
	{"background", color.Background},
	{"dark_background", color.Mantle},
	{"darker_background", color.Crust},
	{"lighter_background", color.Surface0},
	{"", ""},
	{"foreground", color.Foreground},
	{"dark_foreground", color.Overlay0},
	{"light_foreground", color.Subtext1},
	{"bright_foreground", color.ANSI15},
	{"", ""},
	{"red", color.ANSI1},
	{"yellow", color.ANSI3},
	{"orange", color.Peach},
	{"green", color.ANSI2},
	{"cyan", color.ANSI6},
	{"blue", color.ANSI4},
	{"magenta", color.ANSI5},
	{"", ""},
	{"bright_red", color.ANSI9},
	{"bright_yellow", color.ANSI11},
	{"bright_green", color.ANSI10},
	{"bright_cyan", color.ANSI14},
	{"bright_blue", color.ANSI12},
	{"bright_magenta", color.ANSI13},
}

// ColorsTOML is the theme's colors.toml. p must be a complete palette.
func ColorsTOML(t render.Theme, p color.Palette) ([]byte, error) {
	if m := p.Missing(); len(m) > 0 {
		return nil, fmt.Errorf("omarchy: palette is missing %v", m)
	}
	mode := t.Appearance
	if mode != "light" {
		mode = "dark"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# %s, generated by Pult. Pult replaces this file on every apply.\n", t.Name)
	fmt.Fprintf(&b, "mode = %q\n\n", mode)
	for _, k := range keys {
		if k.key == "" {
			b.WriteString("\n")
			continue
		}
		fmt.Fprintf(&b, "%s = %q\n", k.key, p[k.role].Hex())
	}
	return []byte(b.String()), nil
}

// Edits are the theme directory's files, for the change record.
func Edits(home string, t render.Theme, p color.Palette) ([]changes.Edit, error) {
	colors, err := ColorsTOML(t, p)
	if err != nil {
		return nil, err
	}
	dir := ThemeDir(home, t.Slug)
	readme := fmt.Sprintf("# %s\n\nGenerated by Pult from %s. Switch to it with `omarchy-theme-set %s`; `pult uninstall` removes it.\n", Name(t.Slug), t.Name, Name(t.Slug))
	return []changes.Edit{
		{App: "omarchy", Path: filepath.Join(dir, "colors.toml"), Method: "omarchy", Content: colors},
		{App: "omarchy", Path: filepath.Join(dir, "README.md"), Method: "omarchy", Content: []byte(readme)},
	}, nil
}
