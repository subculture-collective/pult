package configedit

import "testing"

func TestYAMLKeys(t *testing.T) {
	const fragment = "# Generated by Pult\ngui:\n  theme:\n    activeBorderColor:\n      - \"#89b4fa\"\n      - bold\n    defaultFgColor:\n      - \"#cdd6f4\"\n"
	paths := []string{"gui.theme"}
	tests := []struct {
		name, src, want, wantErr string
		fragment                 string
	}{
		{
			name: "replace theme, keep siblings and comments",
			src:  "# lazygit\ngui:\n    # my theme\n    theme:\n        activeBorderColor: [red, bold]\n        # old\n        selectedLineBgColor:\n            - blue\n\n    showIcons: true   # icons\ngit:\n    paging:\n        pager: delta\n",
			want: "# lazygit\ngui:\n    # my theme\n    theme:\n        activeBorderColor:\n            - \"#89b4fa\"\n            - bold\n        defaultFgColor:\n            - \"#cdd6f4\"\n\n    showIcons: true   # icons\ngit:\n    paging:\n        pager: delta\n",
		},
		{
			name: "theme is the last key in the file",
			src:  "gui:\n  showIcons: true\n  theme:\n    defaultFgColor: [white]\n",
			want: "gui:\n  showIcons: true\n  theme:\n    activeBorderColor:\n      - \"#89b4fa\"\n      - bold\n    defaultFgColor:\n      - \"#cdd6f4\"\n",
		},
		{
			name: "add theme to an existing gui",
			src:  "gui:\n   showIcons: true\n   nerdFontsVersion: \"3\"\n\nos:\n   editPreset: nvim\n",
			want: "gui:\n   showIcons: true\n   nerdFontsVersion: \"3\"\n   theme:\n      activeBorderColor:\n         - \"#89b4fa\"\n         - bold\n      defaultFgColor:\n         - \"#cdd6f4\"\n\nos:\n   editPreset: nvim\n",
		},
		{
			name: "add gui at the end",
			src:  "# my config\nos:\n  editPreset: nvim",
			want: "# my config\nos:\n  editPreset: nvim\ngui:\n  theme:\n    activeBorderColor:\n      - \"#89b4fa\"\n      - bold\n    defaultFgColor:\n      - \"#cdd6f4\"\n",
		},
		{
			name: "empty file",
			src:  "",
			want: "gui:\n  theme:\n    activeBorderColor:\n      - \"#89b4fa\"\n      - bold\n    defaultFgColor:\n      - \"#cdd6f4\"\n",
		},
		{
			name: "second apply is a no-op",
			src:  "gui:\n  theme:\n    activeBorderColor:\n      - \"#89b4fa\"\n      - bold\n    defaultFgColor:\n      - \"#cdd6f4\"\n  showIcons: true\n",
			want: "gui:\n  theme:\n    activeBorderColor:\n      - \"#89b4fa\"\n      - bold\n    defaultFgColor:\n      - \"#cdd6f4\"\n  showIcons: true\n",
		},
		{
			name:    "flow style",
			src:     "gui: {theme: {defaultFgColor: [white]}}\n",
			wantErr: "flow style",
		},
		{
			name:    "gui is a scalar",
			src:     "gui: off\n",
			wantErr: "not a mapping",
		},
		{
			name:     "fragment key outside paths",
			src:      "",
			fragment: "gui:\n  theme: {}\n  showIcons: false\n",
			wantErr:  `"gui.showIcons" is not in the integration's paths`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			f := tt.fragment
			if f == "" {
				f = fragment
			}
			got, err := YAMLKeys([]byte(tt.src), []byte(f), paths)
			check(t, got, err, tt.want, tt.wantErr)
		})
	}
}

func TestINISet(t *testing.T) {
	tests := []struct {
		name, src, want string
		set             map[string]any
	}{
		{
			name: "btop: replace quoted value",
			src:  "#? Config file for btop v. 1.4.7\n\n#* Name of a btop++/bpytop/bashtop formatted \".theme\" file.\ncolor_theme = \"Default\"\n\ntheme_background = True\n",
			set:  map[string]any{"color_theme": "pult"},
			want: "#? Config file for btop v. 1.4.7\n\n#* Name of a btop++/bpytop/bashtop formatted \".theme\" file.\ncolor_theme = \"pult\"\n\ntheme_background = True\n",
		},
		{
			name: "unquoted value stays unquoted",
			src:  "color_theme=Default\n",
			set:  map[string]any{"color_theme": "TTY"},
			want: "color_theme=TTY\n",
		},
		{
			name: "missing key is appended",
			src:  "theme_background = True",
			set:  map[string]any{"color_theme": "pult"},
			want: "theme_background = True\ncolor_theme = \"pult\"\n",
		},
		{
			name: "commented key is not the key",
			src:  "#color_theme = \"x\"\n",
			set:  map[string]any{"color_theme": "y"},
			want: "#color_theme = \"x\"\ncolor_theme = \"y\"\n",
		},
		{
			name: "section key",
			src:  "[colors]\nfg = 1\n\n[other]\nfg = 2\n",
			set:  map[string]any{"colors.fg": 3, "colors.bg": "x"},
			want: "[colors]\nfg = 3\nbg = \"x\"\n\n[other]\nfg = 2\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := INISet([]byte(tt.src), tt.set)
			check(t, got, err, tt.want, "")
		})
	}
}
