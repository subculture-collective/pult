// hyde themes HyDE with a theme directory, themes/<name>/, selected with
// "hydectl theme set" (or theme.switch.sh). The directory holds what a
// HyDE theme needs (HyDE fa2fd57, .local/lib/hyde/theme.switch.sh and
// color.set.sh): a wallpaper (the switch fails without one; a plain image
// in the background color), hypr.theme with the GTK and icon themes of the
// theme in use (an empty GTK theme makes the switch delete ~/.themes),
// theme.dcol with wallbash's colors, and kitty.theme for exact terminal
// colors.
type hyde struct{}

func (hyde) Name() string { return "hyde" }

var hydeState = regexp.MustCompile(`(?m)^\s*(HYDE_THEME|enableWallDcol)="?([^"\n]*)"?`)

func hydeStaterc(env Env) map[string]string {
	b, _ := os.ReadFile(filepath.Join(stateHome(env), "hyde", "staterc"))
	out := map[string]string{}
	for _, m := range hydeState.FindAllStringSubmatch(string(b), -1) {
		out[m[1]] = m[2]
	}
	return out
}

func hydeSwitcher(env Env) []string {
	if _, err := env.LookPath("hydectl"); err == nil {
		return []string{"hydectl", "theme", "set"}
	}
	script := filepath.Join(env.Home, ".local", "lib", "hyde", "theme.switch.sh")
	if _, err := os.Stat(script); err == nil {
		return []string{script, "-q", "-s"}
	}
	return nil
}

func (hyde) Current(env Env) (string, error) {
	if hydeSwitcher(env) == nil {
		return "", fmt.Errorf("neither hydectl nor ~/.local/lib/hyde/theme.switch.sh is installed")
	}
	cur := hydeStaterc(env)["HYDE_THEME"]
	if cur == "" {
		return "", fmt.Errorf("no current theme in HyDE's staterc")
	}
	return cur, nil
}

var hyprVar = regexp.MustCompile(`(?m)^\s*\$(GTK_THEME|ICON_THEME)\s*=\s*(\S.*?)\s*$`)

func (h hyde) Prepare(env Env, t render.Theme, p color.Palette) ([]changes.Edit, string, string, error) {
	name := themeName(t.Slug)
	themes := filepath.Join(configDir(env), "hyde", "themes")
	// Keep GTK and icons as they are: take them from the theme in use.
	vars := map[string]string{"GTK_THEME": "Wallbash-Gtk", "ICON_THEME": "Adwaita"}
	if cur, err := h.Current(env); err == nil && !strings.HasPrefix(cur, "tender-") {
		b, _ := os.ReadFile(filepath.Join(themes, cur, "hypr.theme"))
		for _, m := range hyprVar.FindAllStringSubmatch(string(b), -1) {
			vars[m[1]] = m[2]
		}
	} else if rec, _ := ReadRecord(env.StateDir, "hyde"); rec != nil {
		b, _ := os.ReadFile(filepath.Join(themes, rec.Previous, "hypr.theme"))
		for _, m := range hyprVar.FindAllStringSubmatch(string(b), -1) {
			vars[m[1]] = m[2]
		}
	}
	mode := "prefer-dark"
	if t.Appearance == "light" {
		mode = "prefer-light"
	}
	rgba := func(r color.Role, alpha string) string { return "rgba(" + p[r].Hex()[1:] + alpha + ")" }
	hypr := fmt.Sprintf(`$HOME/.config/hypr/themes/theme.conf|> $HOME/.config/hypr/themes/colors.conf
# %s, generated by Theme Tender. Theme Tender replaces this file on every apply.

$GTK_THEME = %s
$ICON_THEME = %s
$COLOR_SCHEME = %s

general {
    col.active_border = %s %s 45deg
    col.inactive_border = %s
}

group {
    col.border_active = %s
    col.border_inactive = %s
}
`, t.Name, vars["GTK_THEME"], vars["ICON_THEME"], mode,
		rgba(color.Blue, "ff"), rgba(color.Mauve, "ff"), rgba(color.Surface1, "cc"), rgba(color.Blue, "ff"), rgba(color.Surface1, "cc"))

	var kitty strings.Builder
	kitty.WriteString("$HOME/.config/kitty/theme.conf|killall -SIGUSR1 kitty\n")
	fmt.Fprintf(&kitty, "# %s, generated by Theme Tender.\n", t.Name)
	for _, kv := range [][2]any{{"background", color.Background}, {"foreground", color.Foreground}, {"cursor", color.Cursor},
		{"selection_background", color.SelectionBG}, {"selection_foreground", color.SelectionFG}} {
		fmt.Fprintf(&kitty, "%s %s\n", kv[0], p[kv[1].(color.Role)].Hex())
	}
	for i, r := range color.ANSIRoles {
		fmt.Fprintf(&kitty, "color%d %s\n", i, p[r].Hex())
	}

	var png bytes.Buffer
	if err := solidPNG(&png, p[color.Background]); err != nil {
		return nil, "", "", err
	}
	dir := filepath.Join(themes, name)
	edits := []changes.Edit{
		{Path: filepath.Join(dir, "hypr.theme"), Content: []byte(hypr)},
		{Path: filepath.Join(dir, "kitty.theme"), Content: []byte(kitty.String())},
		{Path: filepath.Join(dir, "theme.dcol"), Content: wallbashDcol(t, p)},
		{Path: filepath.Join(dir, "wallpapers", name+".png"), Content: png.Bytes()},
	}
	note := ""
	if v := hydeStaterc(env)["enableWallDcol"]; v != "" && v != "0" {
		note = "HyDE takes colors from the wallpaper (wallbash mode " + v + "); switch it to theme mode to see this theme's colors"
	}
	return edits, name, note, nil
}

func (hyde) Switch(env Env, sel string) [][]string {
	sw := hydeSwitcher(env)
	if sw == nil {
		return nil
	}
	return [][]string{append(sw, sel)}
}

func solidPNG(w *bytes.Buffer, c color.RGB) error {
	hex := c.Hex()
	var r, g, b uint8
	fmt.Sscanf(hex, "#%02x%02x%02x", &r, &g, &b)
	img := image.NewRGBA(image.Rect(0, 0, 64, 64))
	for i := 0; i < len(img.Pix); i += 4 {
		img.Pix[i], img.Pix[i+1], img.Pix[i+2], img.Pix[i+3] = r, g, b, 0xff
	}
	return png.Encode(w, img)
}

// wallbashDcol is a theme.dcol: four primary colors from dark to light (in
// a dark theme) with a text color each, and nine shades of each from dark
// to light, as wallbash.sh writes them (no "#"; rgba as "rgba(r,g,b,\1)").
func wallbashDcol(t render.Theme, p color.Palette) []byte {
	mode := "dark"
	if t.Appearance == "light" {
		mode = "light"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "dcol_mode=%q\n", mode)
	bare := func(c color.RGB) string { return c.Hex()[1:] }
	rgba := func(c color.RGB) string {
		var r, g, bl int
		fmt.Sscanf(c.Hex(), "#%02x%02x%02x", &r, &g, &bl)
		return fmt.Sprintf(`rgba(%d,%d,%d,\1)`, r, g, bl)
	}
	put := func(key string, c color.RGB) {
		fmt.Fprintf(&b, "%s=\"%s\"\n%s_rgba=\"%s\"\n", key, bare(c), key, rgba(c))
	}
	neutrals := []color.Role{color.Crust, color.Mantle, color.Base, color.Surface0, color.Surface1, color.Surface2, color.Overlay0, color.Overlay1, color.Overlay2}
	primaries := []struct {
		pry, txt color.Role
		shades   []color.RGB
	}{
		{color.Base, color.Text, nil},
		{color.Surface0, color.Text, nil},
		{color.Mauve, color.Base, ramp(p[color.Mauve])},
		{color.Blue, color.Base, ramp(p[color.Blue])},
	}
	for i, pr := range primaries {
		n := i + 1
		put(fmt.Sprintf("dcol_pry%d", n), p[pr.pry])
		put(fmt.Sprintf("dcol_txt%d", n), p[pr.txt])
		for k := 0; k < 9; k++ {
			c := p[neutrals[k]]
			if pr.shades != nil {
				c = pr.shades[k]
			}
			put(fmt.Sprintf("dcol_%dxa%d", n, k+1), c)
		}
	}
	return []byte(b.String())
}

// ramp is nine shades of c's hue, from dark to light, at c's chroma.
func ramp(c color.RGB) []color.RGB {
	lch := c.OKLCH()
	out := make([]color.RGB, 9)
	for i := range out {
		l := lch
		l.L = 0.25 + 0.0875*float64(i) // 0.25 … 0.95
		out[i] = l.MapToGamut()
	}
	return out
}

// caelestia has no place for custom schemes ("caelestia scheme set -n"
// takes packaged names only; caelestia-dots/cli 6bde2df, paths.py and
// utils/scheme.py), so for catalog themes it ships it switches to its own
// copy, and leaves Caelestia alone otherwise. A selection is
// "name flavour mode variant", as "caelestia scheme get -nfmv" prints it.
type caelestia struct{}

func (caelestia) Name() string { return "caelestia" }

// caelestiaSchemes maps catalog theme IDs to Caelestia's packaged schemes
// (src/caelestia/data/schemes/<name>/<flavour>/<mode>.txt).
var caelestiaSchemes = map[string][3]string{
	"catppuccin-mocha":     {"catppuccin", "mocha", "dark"},
	"catppuccin-macchiato": {"catppuccin", "macchiato", "dark"},
	"catppuccin-frappe":    {"catppuccin", "frappe", "dark"},
	"catppuccin-latte":     {"catppuccin", "latte", "light"},
	"dracula":              {"dracula", "medium", "dark"},
	"nord":                 {"nord", "medium", "dark"},
	"gruvbox-dark":         {"gruvbox", "medium", "dark"},
	"rose-pine":            {"rosepine", "main", "dark"},
	"rose-pine-moon":       {"rosepine", "moon", "dark"},
	"rose-pine-dawn":       {"rosepine", "dawn", "light"},
	"tokyo-night-dark":     {"tokyonight", "medium", "dark"},
	"everforest-dark":      {"everforest", "medium", "dark"},
	"everforest-dark-hard": {"everforest", "hard", "dark"},
	"everblush":            {"everblush", "medium", "dark"},
	"atom-one-dark":        {"onedark", "default", "dark"},
}

func (caelestia) Current(env Env) (string, error) {
	out, err := call(env, "Caelestia", "caelestia", "scheme", "get", "-n", "-f", "-m", "-v")
	if err != nil {
		return "", err
	}
	f := strings.Fields(out)
	if len(f) != 4 {
		return "", fmt.Errorf("caelestia scheme get printed %q, not name, flavour, mode and variant", out)
	}
	return strings.Join(f, " "), nil
}

func (c caelestia) Prepare(env Env, t render.Theme, _ color.Palette) ([]changes.Edit, string, string, error) {
	s, ok := caelestiaSchemes[t.Slug]
	if !ok {
		return nil, "", "Caelestia left alone: it has no scheme for " + t.Name + " and no place for custom ones", nil
	}
	variant := "tonalspot"
	if cur, err := c.Current(env); err == nil {
		variant = strings.Fields(cur)[3] // keep the user's variant
	}
	return nil, strings.Join([]string{s[0], s[1], s[2], variant}, " "), "Caelestia uses its own copy of " + t.Name, nil
}

func (caelestia) Switch(env Env, sel string) [][]string {
	f := strings.Fields(sel)
	if len(f) != 4 {
		return nil
	}
	return [][]string{{"caelestia", "scheme", "set", "-n", f[0], "-f", f[1], "-m", f[2], "-v", f[3]}}
}

// end4 passes the palette's accent to end-4's own generator, switchwall.sh
// --noswitch --color (dots-hyprland 2f2a376), which derives everything
// else from it; end-4 takes no full palette. The script needs the
// Hyprland session's environment. A selection is the accent, or "clear"
// for colors from the wallpaper.
type end4 struct{}

func (end4) Name() string { return "end-4" }

func end4Script(env Env) string {
	return filepath.Join(configDir(env), "quickshell", "ii", "scripts", "colors", "switchwall.sh")
}

func (end4) Current(env Env) (string, error) {
	if _, err := os.Stat(end4Script(env)); err != nil {
		return "", fmt.Errorf("end-4's switchwall.sh is not installed")
	}
	if env.Getenv("HYPRLAND_INSTANCE_SIGNATURE") == "" || env.Getenv("ILLOGICAL_IMPULSE_VIRTUAL_ENV") == "" {
		return "", fmt.Errorf("%w; end-4's color script needs it, so run tender apply from a terminal in the session", errNoSession)
	}
	b, err := os.ReadFile(filepath.Join(configDir(env), "illogical-impulse", "config.json"))
	if err != nil {
		return "clear", nil
	}
	var cfg struct {
		Appearance struct {
			Palette struct {
				AccentColor string `json:"accentColor"`
			} `json:"palette"`
		} `json:"appearance"`
	}
	if json.Unmarshal(b, &cfg) != nil || cfg.Appearance.Palette.AccentColor == "" {
		return "clear", nil
	}
	return strings.ToLower(cfg.Appearance.Palette.AccentColor), nil
}

func (end4) Prepare(env Env, t render.Theme, p color.Palette) ([]changes.Edit, string, string, error) {
	return nil, p[color.Blue].Hex(), "end-4 takes one accent color and derives the rest itself", nil
}

func (end4) Switch(env Env, sel string) [][]string {
	return [][]string{{end4Script(env), "--noswitch", "--color", sel}}
}
